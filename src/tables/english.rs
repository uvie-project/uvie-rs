//! English word override dictionary.
//!
//! English words that produce valid-looking Vietnamese syllables when typed
//! through the Telex/VNI engine, but should pass through as English instead.
//! These are words where the engine applies tone/modifier transforms because
//! intermediate states happen to be valid Vietnamese, but the result is
//! garbled (Vietnamese prefix + English suffix, e.g. "character" → "chẩcter",
//! "safari" → "sầri", "good" → "gôd").
//!
//! The check fires per-keystroke and at word boundaries, so it has minimal
//! impact on performance (gated by word_raw.len() >= 4). Lookup is O(log n)
//! binary search on a sorted static array — no heap, no dependencies.
//!
//! Excluded: words whose transform is a real Vietnamese word (from 22k word
//! list) or whose V-C-V split components are both valid Vietnamese words
//! (e.g. "chaos" → "cháo", "user" → "u" + "sẻ"). Also excluded unless common
//! (top ~10k corpus rank): words shadowing a real Telex sequence as a prefix
//! and words ending in a doubled tone key (ss/ff/rr/xx/jj) — the double
//! cancel must keep working (cass → cas, timff → timf), so the dict only
//! protects the ones users actually type (pass, mass, boss).

