/// Compare `word` against a table entry, case-insensitively: the tables store
/// lowercase, and a render can be capitalized ("Nó", "NÓ").
#[inline]
fn compare_lowercase(word: &str, entry: &str) -> Ordering {
    let mut ei = entry.chars();
    for wc in word.chars() {
        let wc = wc.to_lowercase().next().unwrap_or(wc);
        match ei.next() {
            Some(ec) => match wc.cmp(&ec) {
                Ordering::Equal => continue,
                ord => return ord,
            },
            None => return Ordering::Greater,
        }
    }
    if ei.next().is_some() {
        Ordering::Less
    } else {
        Ordering::Equal
    }
}

/// Returns `true` when `word` (a rendered syllable, any case) is one of the
/// highest-frequency Vietnamese syllables/particles.
///
/// Case-insensitive. Only called at word boundaries (space/commit).
#[inline]
pub fn is_top_vietnamese_syllable(word: &str) -> bool {
    let mut lo = 0usize;
    let mut hi = VIETNAMESE_TOP_SYLLABLES.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match compare_lowercase(word, VIETNAMESE_TOP_SYLLABLES[mid]) {
            Ordering::Equal => return true,
            Ordering::Less => hi = mid,
            Ordering::Greater => lo = mid + 1,
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_is_sorted_and_deduped() {
        for pair in VIETNAMESE_TOP_SYLLABLES.windows(2) {
            assert!(pair[0] < pair[1], "{:?} then {:?}", pair[0], pair[1]);
        }
    }

    #[test]
    fn lookup_is_case_insensitive() {
        assert!(is_top_vietnamese_syllable("nó"));
        assert!(is_top_vietnamese_syllable("Nó"));
        assert!(is_top_vietnamese_syllable("NÓ"));
        assert!(is_top_vietnamese_syllable("em"));
        assert!(!is_top_vietnamese_syllable("noss"));
        assert!(!is_top_vietnamese_syllable(""));
    }
}
