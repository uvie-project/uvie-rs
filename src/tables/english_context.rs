//! Sentence-context English preference tables.
//!
//! Two sorted tables back the sentence-context English restore rule at
//! word commit (`Diffable::commit_diff`): when the PREVIOUS committed
//! word is clearly English, a common English word that the pipeline
//! marked as Vietnamese is restored to its raw keystrokes
//! ("Hello, how are you?" must not render "Hello, hơ are you?").
//!
//! - `ENGLISH_CONTEXT_WORDS` — words that, as the previous committed
//!   word, signal English context. From the first 10,000 lines of
//!   `tests/data/english_100k.txt`: lowercase ASCII letters (apostrophe
//!   allowed) that the engine passes through UNCHANGED (feed_diff
//!   render == raw, English override off), excluding every whitespace
//!   token of `tests/data/vietnamese_22k.txt` (lowercased — a
//!   Vietnamese word must never flip the context) and the curated
//!   loanword list commonly mixed into Vietnamese sentences (ok, file,
//!   email, app, deadline, ...).
//! - `ENGLISH_AMBIGUOUS_WORDS` — restore candidates: same first 10,000
//!   lines, lowercase ASCII letters, length >= 2, whose engine render
//!   differs from the raw and contains a non-ASCII char, and that are
//!   NOT already in `ENGLISH_OVERRIDES` (the per-word dictionary path
//!   handles those).
//!
//! Both are sorted and looked up with a binary search (case-insensitive),
//! so the cost is paid only at word commit, never per keystroke.
//!
//! Regenerate with:
//! `cargo run --release --example gen_context -- src/tables/english_context.rs`

