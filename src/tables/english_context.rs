/// Compare a `[char]` slice against a `&str`, case-insensitively.
/// Returns `Equal` if they match (ignoring case), `Less`/`Greater` otherwise.
#[inline]
fn compare_chars_to_str(chars: &[char], s: &str) -> Ordering {
    let mut si = s.chars();
    for &c in chars {
        match si.next() {
            Some(sc) => match c.to_ascii_lowercase().cmp(&sc.to_ascii_lowercase()) {
                Ordering::Equal => continue,
                ord => return ord,
            },
            None => return Ordering::Greater,
        }
    }
    if si.next().is_some() {
        Ordering::Less
    } else {
        Ordering::Equal
    }
}

/// Compare two `&str`s case-insensitively (Unicode lowercase, so
/// "VIỆT" matches the stored "việt").
#[inline]
fn compare_str_to_str(a: &str, b: &str) -> Ordering {
    let mut bi = b.chars();
    for ac in a.chars() {
        let ac = ac.to_lowercase().next().unwrap_or(ac);
        match bi.next() {
            Some(bc) => match ac.cmp(&bc) {
                Ordering::Equal => continue,
                ord => return ord,
            },
            None => return Ordering::Greater,
        }
    }
    if bi.next().is_some() {
        Ordering::Less
    } else {
        Ordering::Equal
    }
}

#[inline]
fn find_chars(table: &[&str], word: &[char]) -> Option<usize> {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match compare_chars_to_str(word, table[mid]) {
            Ordering::Equal => return Some(mid),
            Ordering::Less => hi = mid,
            Ordering::Greater => lo = mid + 1,
        }
    }
    None
}

#[inline]
fn contains_chars(table: &[&str], word: &[char]) -> bool {
    find_chars(table, word).is_some()
}

#[inline]
fn contains_str(table: &[&str], word: &str) -> bool {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match compare_str_to_str(word, table[mid]) {
            Ordering::Equal => return true,
            Ordering::Less => hi = mid,
            Ordering::Greater => lo = mid + 1,
        }
    }
    false
}

/// Returns `true` when `word` (the previous committed word, as rendered
/// on screen) marks the sentence context as English.
///
/// Case-insensitive. Uses binary search on a sorted static array.
/// Only called at word boundaries (space/commit), never per-keystroke.
#[inline]
pub fn is_english_context_word(word: &str) -> bool {
    !word.is_empty() && contains_str(ENGLISH_CONTEXT_WORDS, word)
}

/// Returns `true` when `word` (as a char slice of the raw keystrokes)
/// is a common English word the pipeline may have marked as Vietnamese.
///
/// Case-insensitive. Uses binary search on a sorted static array.
/// Only called at word boundaries (space/commit), never per-keystroke.
#[inline]
pub fn is_english_ambiguous_word(word: &[char]) -> bool {
    english_ambiguous_score(word).is_some()
}

/// Vietnamese rarity score of `word`'s render: 0 when the render is not a
/// Vietnamese token at all, 21 for "ít", 2 for "tét". `None` when the
/// word is not an English restore candidate.
///
/// Case-insensitive. Only called at word boundaries (space/commit).
#[inline]
pub fn english_ambiguous_score(word: &[char]) -> Option<u8> {
    if word.len() < 2 {
        return None;
    }
    let mut lo = 0usize;
    let mut hi = ENGLISH_AMBIGUOUS_WORDS.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match compare_chars_to_str(word, ENGLISH_AMBIGUOUS_WORDS[mid].0) {
            Ordering::Equal => return Some(ENGLISH_AMBIGUOUS_WORDS[mid].1),
            Ordering::Less => hi = mid,
            Ordering::Greater => lo = mid + 1,
        }
    }
    None
}

/// Returns `true` when `word` (as a char slice of the raw keystrokes) is
/// an English word containing a doubled Telex tone key ("off", "diff").
///
/// Case-insensitive. Only called at word boundaries (space/commit).
#[inline]
pub fn is_english_doubled_key_word(word: &[char]) -> bool {
    !word.is_empty() && contains_chars(ENGLISH_DOUBLED_KEY_WORDS, word)
}

/// Returns `true` when `word` (a rendered syllable, any case) is a common
/// Vietnamese token — seen at least 6 times in the word list.
///
/// Only called at word boundaries (space/commit).
#[inline]
pub fn is_common_vietnamese_syllable(word: &str) -> bool {
    !word.is_empty() && contains_str(VIETNAMESE_COMMON_SYLLABLES, word)
}

/// Returns `true` when `word` (the previous committed word, as rendered)
/// is a curated English loanword Vietnamese speakers mix into Vietnamese
/// sentences: the sentence is still Vietnamese.
///
/// Case-insensitive. Only called at word boundaries (space/commit).
#[inline]
pub fn is_vietnamese_loanword(word: &str) -> bool {
    !word.is_empty() && contains_str(VIETNAMESE_LOANWORDS, word)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_context_lookup() {
        assert!(is_english_context_word("hello"));
        assert!(is_english_context_word("YOU")); // case-insensitive
        assert!(is_english_context_word("are"));
        assert!(is_english_context_word("it"));
        assert!(is_english_context_word("hi")); // forced context word
        assert!(!is_english_context_word("than")); // a Vietnamese token
        assert!(!is_english_context_word("file")); // curated loanword
        assert!(!is_english_context_word(""));
    }

    #[test]
    fn test_ambiguous_lookup() {
        assert!(is_english_ambiguous_word(&['h', 'o', 'w']));
        assert!(is_english_ambiguous_word(&['B', 'E', 'S', 'T'])); // case-insensitive
        assert!(is_english_ambiguous_word(&['a', 's']));
        assert!(!is_english_ambiguous_word(&['a'])); // too short
        assert!(!is_english_ambiguous_word(&['x', 'y', 'z', 'z']));
        assert!(!is_english_ambiguous_word(&[]));
    }

    #[test]
    fn test_ambiguous_scores() {
        // Rare Vietnamese readings: the English word wins.
        assert_eq!(english_ambiguous_score(&['t', 'e', 's', 't']), Some(2));
        assert_eq!(english_ambiguous_score(&['o', 'f']), Some(1));
        assert_eq!(english_ambiguous_score(&['o', 'r']), Some(0));
        // A common Vietnamese syllable scores high.
        assert!(english_ambiguous_score(&['i', 't', 's']).unwrap() >= 6);
        assert_eq!(english_ambiguous_score(&['a']), None);
        assert_eq!(english_ambiguous_score(&['x', 'y', 'z', 'z']), None);
    }

    #[test]
    fn test_doubled_key_lookup() {
        for w in ["off", "diff", "lossless", "affair", "affect"] {
            let chars: Vec<char> = w.chars().collect();
            assert!(is_english_doubled_key_word(&chars), "{w}");
        }
        // Words the cancel sequence leaves alone have nothing to fix.
        for w in ["staff", "process", "class"] {
            let chars: Vec<char> = w.chars().collect();
            assert!(!is_english_doubled_key_word(&chars), "{w}");
        }
        // "masster" is not an English word: the double-s cancel must stay.
        assert!(!is_english_doubled_key_word(&[
            'm', 'a', 's', 's', 't', 'e', 'r'
        ]));
        assert!(!is_english_doubled_key_word(&[
            'm', 'a', 's', 't', 'e', 'r'
        ]));
        assert!(!is_english_doubled_key_word(&[]));
    }

    #[test]
    fn test_common_syllables() {
        assert!(is_common_vietnamese_syllable("việt"));
        assert!(is_common_vietnamese_syllable("VIỆT"));
        assert!(is_common_vietnamese_syllable("hà"));
        assert!(!is_common_vietnamese_syllable("jỉa")); // JIRA's render
        assert!(!is_common_vietnamese_syllable(""));
    }

    #[test]
    fn test_loanword_lookup() {
        assert!(is_vietnamese_loanword("ok"));
        assert!(is_vietnamese_loanword("file"));
        assert!(is_vietnamese_loanword("OK")); // case-insensitive
        assert!(!is_vietnamese_loanword("hello"));
        assert!(!is_vietnamese_loanword(""));
    }

    #[test]
    fn tables_are_sorted_and_lowercase() {
        for w in ENGLISH_CONTEXT_WORDS
            .iter()
            .chain(ENGLISH_DOUBLED_KEY_WORDS)
            .chain(VIETNAMESE_COMMON_SYLLABLES)
            .chain(VIETNAMESE_LOANWORDS)
        {
            assert!(w.chars().all(|c| !c.is_ascii_uppercase()));
        }
        for (w, _) in ENGLISH_AMBIGUOUS_WORDS {
            assert!(w.chars().all(|c| c.is_ascii_lowercase()));
        }
        assert!(ENGLISH_CONTEXT_WORDS.windows(2).all(|w| w[0] < w[1]));
        assert!(ENGLISH_DOUBLED_KEY_WORDS.windows(2).all(|w| w[0] < w[1]));
        assert!(VIETNAMESE_COMMON_SYLLABLES.windows(2).all(|w| w[0] < w[1]));
        assert!(VIETNAMESE_LOANWORDS.windows(2).all(|w| w[0] < w[1]));
        assert!(ENGLISH_AMBIGUOUS_WORDS.windows(2).all(|w| w[0].0 < w[1].0));
    }
}
