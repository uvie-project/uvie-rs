//! English restore tables shared by the word-commit rules.
//!
//! Four sorted tables back the English restore rules at word commit
//! (`Diffable::commit_with_boundary_diff`), all gated by the host's
//! "restore English" setting:
//!
//! - `ENGLISH_CONTEXT_WORDS` — words that, as the previous committed
//!   word, signal English context. From the first 10,000 lines of
//!   `tests/data/english_100k.txt`: lowercase ASCII letters (apostrophe
//!   allowed) that the engine passes through UNCHANGED (feed_diff
//!   render == raw, English override off), excluding every whitespace
//!   token of `tests/data/vietnamese_22k.txt` (lowercased — a
//!   Vietnamese word must never flip the context) and the curated
//!   loanword list commonly mixed into Vietnamese sentences (ok, file,
//!   email, app, deadline, ...).
//! - `ENGLISH_AMBIGUOUS_WORDS` — restore candidates with their
//!   Vietnamese rarity score: the first 20,000 lines, lowercase ASCII
//!   letters, length >= 2, whose engine render differs from the raw and
//!   contains a non-ASCII char, and that are NOT already in
//!   `ENGLISH_OVERRIDES` (the per-word dictionary path handles those).
//!   The score is the number of whitespace tokens of
//!   `tests/data/vietnamese_22k.txt` equal to the lowercased render
//!   ("ít" 21, "tét" 2, "ỏ" 0): a low score means the Vietnamese
//!   reading is essentially unused, so the English word wins.
//! - `ENGLISH_DOUBLED_KEY_WORDS` — English words containing a doubled
//!   Telex tone key pair (ss ff rr xx jj) whose render differs from
//!   the raw. The doubled key is the Telex cancel sequence, so
//!   "off" renders "of" and "diff" renders "dif"; a real English
//!   word must show its literal keystrokes.
//! - `VIETNAMESE_COMMON_SYLLABLES` — lowercased Vietnamese tokens seen
//!   at least 6 times. An ALL-CAPS acronym whose render is a rare
//!   syllable ("JIRA" → "JỈA") is English; one whose render is a
//!   common syllable ("VIỆT") is Vietnamese.
//!
//! All are sorted and looked up with a binary search (case-insensitive),
//! so the cost is paid only at word commit, never per keystroke.
//!
//! Regenerate with:
//! `cargo run --release --example gen_context -- src/tables/english_context.rs`

