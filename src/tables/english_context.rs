/// Compare a `[char]` slice against a `&str`, case-insensitively.
/// Returns `Equal` if they match (ignoring case), `Less`/`Greater` otherwise.
#[inline]
fn compare_chars_to_str(chars: &[char], s: &str) -> Ordering {
    let mut si = s.chars();
    for &c in chars {
        match si.next() {
            Some(sc) => match c.to_ascii_lowercase().cmp(&sc.to_ascii_lowercase()) {
                Ordering::Equal => continue,
                ord => return ord,
            },
            None => return Ordering::Greater,
        }
    }
    if si.next().is_some() {
        Ordering::Less
    } else {
        Ordering::Equal
    }
}

/// Compare two `&str`s case-insensitively (ASCII case folding).
#[inline]
fn compare_str_to_str(a: &str, b: &str) -> Ordering {
    let mut bi = b.chars();
    for ac in a.chars() {
        match bi.next() {
            Some(bc) => match ac.to_ascii_lowercase().cmp(&bc.to_ascii_lowercase()) {
                Ordering::Equal => continue,
                ord => return ord,
            },
            None => return Ordering::Greater,
        }
    }
    if bi.next().is_some() {
        Ordering::Less
    } else {
        Ordering::Equal
    }
}

#[inline]
fn contains_chars(table: &[&str], word: &[char]) -> bool {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match compare_chars_to_str(word, table[mid]) {
            Ordering::Equal => return true,
            Ordering::Less => hi = mid,
            Ordering::Greater => lo = mid + 1,
        }
    }
    false
}

#[inline]
fn contains_str(table: &[&str], word: &str) -> bool {
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        match compare_str_to_str(word, table[mid]) {
            Ordering::Equal => return true,
            Ordering::Less => hi = mid,
            Ordering::Greater => lo = mid + 1,
        }
    }
    false
}

/// Returns `true` when `word` (the previous committed word, as rendered
/// on screen) marks the sentence context as English.
///
/// Case-insensitive. Uses binary search on a sorted static array.
/// Only called at word boundaries (space/commit), never per-keystroke.
#[inline]
pub fn is_english_context_word(word: &str) -> bool {
    !word.is_empty() && contains_str(ENGLISH_CONTEXT_WORDS, word)
}

/// Returns `true` when `word` (as a char slice of the raw keystrokes)
/// is a common English word the pipeline may have marked as Vietnamese.
///
/// Case-insensitive. Uses binary search on a sorted static array.
/// Only called at word boundaries (space/commit), never per-keystroke.
#[inline]
pub fn is_english_ambiguous_word(word: &[char]) -> bool {
    word.len() >= 2 && contains_chars(ENGLISH_AMBIGUOUS_WORDS, word)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_context_lookup() {
        assert!(is_english_context_word("hello"));
        assert!(is_english_context_word("YOU")); // case-insensitive
        assert!(is_english_context_word("are"));
        assert!(is_english_context_word("it"));
        assert!(is_english_context_word("hi")); // forced context word
        assert!(!is_english_context_word("than")); // a Vietnamese token
        assert!(!is_english_context_word("file")); // curated loanword
        assert!(!is_english_context_word(""));
    }

    #[test]
    fn test_ambiguous_lookup() {
        assert!(is_english_ambiguous_word(&['h', 'o', 'w']));
        assert!(is_english_ambiguous_word(&['B', 'E', 'S', 'T'])); // case-insensitive
        assert!(is_english_ambiguous_word(&['a', 's']));
        assert!(!is_english_ambiguous_word(&['a'])); // too short
        assert!(!is_english_ambiguous_word(&['x', 'y', 'z', 'z']));
        assert!(!is_english_ambiguous_word(&[]));
    }

    #[test]
    fn tables_are_sorted_and_lowercase() {
        for w in ENGLISH_CONTEXT_WORDS.iter().chain(ENGLISH_AMBIGUOUS_WORDS) {
            assert!(w.chars().all(|c| c.is_ascii_lowercase() || c == '\''));
        }
        assert!(ENGLISH_CONTEXT_WORDS.windows(2).all(|w| w[0] < w[1]));
        assert!(ENGLISH_AMBIGUOUS_WORDS.windows(2).all(|w| w[0] < w[1]));
    }
}
